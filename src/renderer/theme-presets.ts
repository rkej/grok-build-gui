type ThemeTokenName = (typeof themeTokenNames)[number];
type ThemeTokenMap = Partial<Record<ThemeTokenName, string>>;

export interface ThemePreset {
  readonly id: ThemePresetId;
  readonly name: string;
  readonly description: string;
  readonly swatches: readonly string[];
  readonly variants: Readonly<Record<ResolvedTheme, { readonly label: string; readonly tokens: ThemeTokenMap }>>;
}

