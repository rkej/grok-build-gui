function preset(
  id: ThemePresetId,
  name: string,
  description: string,
  swatches: readonly string[],
  light: ThemeTokenMap,
  dark: ThemeTokenMap,
): ThemePreset {
  return {
    id,
    name,
    description,
    swatches,
    variants: {
      light: { label: `${name} light`, tokens: light },
      dark: { label: `${name} dark`, tokens: dark },
    },
  };
}

